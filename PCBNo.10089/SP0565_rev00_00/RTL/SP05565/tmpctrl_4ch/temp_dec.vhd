library IEEE;
use IEEE.STD_LOGIC_1164.ALL;

entity temp_dec is
	port ( REGSEL :in std_logic;
	       LA :in std_logic_vector(4 downto 0);
			 SEL :out std_logic_vector(31 downto 0));
end temp_dec;

architecture RTL of temp_dec is

signal COMP :std_logic_vector(5 downto 0);

begin

COMP <= REGSEL & LA;

process (COMP) begin
	case COMP is
		when "100000" => SEL <= "00000000000000000000000000000001";--00h
		when "100001" => SEL <= "00000000000000000000000000000010";--01h
		when "100010" => SEL <= "00000000000000000000000000000100";--02
		when "100011" => SEL <= "00000000000000000000000000001000";--03h
		when "100100" => SEL <= "00000000000000000000000000010000";--04h
		when "100101" => SEL <= "00000000000000000000000000100000";--05h
		when "100110" => SEL <= "00000000000000000000000001000000";--06h
		when "100111" => SEL <= "00000000000000000000000010000000";--07h
		when "101000" => SEL <= "00000000000000000000000100000000";--08h
		when "101001" => SEL <= "00000000000000000000001000000000";--09h
		when "101010" => SEL <= "00000000000000000000010000000000";--0Ah
		when "101011" => SEL <= "00000000000000000000100000000000";--0Bh
		when "101100" => SEL <= "00000000000000000001000000000000";--0Ch
		when "101101" => SEL <= "00000000000000000010000000000000";--0Dh
		when "101110" => SEL <= "00000000000000000100000000000000";--0Eh
		when "101111" => SEL <= "00000000000000001000000000000000";--0Fh
		when "110000" => SEL <= "00000000000000010000000000000000";--10h
		when "110001" => SEL <= "00000000000000100000000000000000";--11h
		when "110010" => SEL <= "00000000000001000000000000000000";--12h
		when "110011" => SEL <= "00000000000010000000000000000000";--13h
		when "110100" => SEL <= "00000000000100000000000000000000";--14h
		when "110101" => SEL <= "00000000001000000000000000000000";--15h
		when "110110" => SEL <= "00000000010000000000000000000000";--16h
		when "110111" => SEL <= "00000000100000000000000000000000";--17h
		when "111000" => SEL <= "00000001000000000000000000000000";--18h
		when "111001" => SEL <= "00000010000000000000000000000000";--19h
		when "111010" => SEL <= "00000100000000000000000000000000";--1Ah
		when "111011" => SEL <= "00001000000000000000000000000000";--1Bh
		when "111100" => SEL <= "00010000000000000000000000000000";--1Ch
		when "111101" => SEL <= "00100000000000000000000000000000";--1Dh
		when "111110" => SEL <= "01000000000000000000000000000000";--1Eh
		when "111111" => SEL <= "10000000000000000000000000000000";--1Fh
		when others   => SEL <= "00000000000000000000000000000000";
	end case;
end process;

end RTL;
